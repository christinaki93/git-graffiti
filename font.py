class UnknownGlyph(ValueError):
    """Raised for a character the font has no glyph for."""


def render_text(text, spacing=1):
    """Render `text` as a list of 7 strings of '#' and '.'.

    Lookup is case-insensitive. Raises UnknownGlyph for unsupported characters
    so a typo fails loudly rather than silently dropping a letter.
    """
    rows = [""] * GLYPH_HEIGHT
    gap = "." * spacing
    for i, char in enumerate(text):
        glyph = GLYPHS.get(char.upper())
        if glyph is None:
            raise UnknownGlyph(
                "no glyph for %r; supported: %s"
                % (char, " ".join(sorted(GLYPHS)))
            )
        for r in range(GLYPH_HEIGHT):
            rows[r] += (gap if i else "") + glyph[r]
    return rows
